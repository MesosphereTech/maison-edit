export const curatedScenarioFor = (profile = {}) =>
  curatedScenarios.find((scenario) =>
    ["personaId", "homeId", "room"].every(
      (key) => scenario[key] === profile[key],
    ),
  ) || null;

export function personalizedSceneFor(skuId, profile, color) {
  const scenario = curatedScenarioFor(profile);
  const scene = scenario?.products.find(
    (entry) => entry.skuId === skuId && (!color || entry.color === color),
  );
  return scene
    ? {
        ...scene,
        scenarioId: scenario.id,
        personaId: scenario.personaId,
        homeId: scenario.homeId,
        src: `/personalized-scenes/${scene.file}`,
      }
    : null;
}

// A reversible, viewport-relative dissolve. Entering at the bottom shows the
// original packshot; carrying the image toward the reading band reveals its
// prepared scene. No video, live image generation, fit or measurement is implied.
export function sceneScrollProgress(
  rect,
  viewportHeight,
  reduced = false,
  entryCenter = viewportHeight * 0.98,
) {
  if (!rect || !Number.isFinite(viewportHeight) || viewportHeight <= 0)
    return 0;
  const center = rect.top + rect.height / 2;
  const progress = Math.min(
    1,
    Math.max(0, (entryCenter - center) / (viewportHeight * 0.26)),
  );
  return reduced ? Number(progress >= 0.5) : progress;
}
